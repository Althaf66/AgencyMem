// `pnpm list:cypher` (task 6.7): writes the list of every .cypher file into README.md, between
// the cypher markers, so the README lists the real queries (technical design, import rule 4).
// `--check` changes nothing and exits 1 when the README's list is out of date.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CYPHER = "packages/graph/cypher";
const README = join(ROOT, "README.md");
const START = "<!-- cypher:start -->";
const END = "<!-- cypher:end -->";

/** The six queries that carry the product (technical design, "Key Cypher queries"). */
const KEY = [
  "write/claim-task",
  "write/write-versioned",
  "write/supersede-fact",
  "read/impact",
  "read/why",
  "read/evidence",
];
const GROUPS = [
  ["schema", "Schema"],
  ["read", "Read queries"],
  ["write", "Write queries (sent only by packages/memory)"],
] as const;

/**
 * The first sentence of a file's leading `//` comment, or "" when it has none. A `.` after a lone
 * number ("one query: 1. ...") numbers a step; it does not end the sentence.
 */
function describe(text: string): string {
  const lines: string[] = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith("//")) break;
    lines.push(line.replace(/^\/\/\s?/, ""));
  }
  const comment = lines.join(" ").replace(/\s+/g, " ").trim();
  const end = comment.search(/(?<!\b\d)\.(\s|$)/);
  return end < 0 ? comment : comment.slice(0, end + 1);
}

/** Every .cypher file as `read/impact`, with its link and description, sorted by name. */
function queries() {
  const files = (readdirSync(join(ROOT, CYPHER), { recursive: true }) as string[])
    .filter((f) => f.endsWith(".cypher"))
    .map((f) => f.replaceAll("\\", "/"))
    .sort();
  return files.map((f) => ({
    name: f.slice(0, -".cypher".length),
    link: `${CYPHER}/${f}`,
    description: describe(readFileSync(join(ROOT, CYPHER, f), "utf8")),
  }));
}

const line = (q: ReturnType<typeof queries>[number]) =>
  `- [\`${q.name}\`](${q.link})${q.description ? `: ${q.description}` : ""}`;

/** The generated list, markers included. */
export function cypherBlock(): string {
  const all = queries();
  const key = KEY.map((name) => all.find((q) => q.name === name)!);
  const parts = [
    START,
    "", // prettier keeps a blank line after the marker and before the end one
    `${all.length} files under \`${CYPHER}/\`. Generated by \`pnpm list:cypher\`; do not edit by hand.`,
    "",
    "### The six queries that carry the product",
    "",
    ...key.map(line),
  ];
  for (const [dir, title] of GROUPS) {
    parts.push(
      "",
      `### ${title}`,
      "",
      ...all.filter((q) => q.name.startsWith(`${dir}/`)).map(line),
    );
  }
  parts.push("", END);
  return parts.join("\n");
}

/** The list as the README holds it now, markers included ("" when the markers are missing). */
export function readmeBlock(readme: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  return start < 0 || end < 0 ? "" : readme.slice(start, end + END.length);
}

function main(): number {
  const readme = readFileSync(README, "utf8");
  const now = readmeBlock(readme);
  if (!now) {
    console.error(`list:cypher: README.md has no ${START} ... ${END} markers`);
    return 1;
  }
  const next = cypherBlock();
  if (process.argv.includes("--check")) {
    if (now === next) return 0;
    console.error("list:cypher: README.md's Cypher list is out of date; run `pnpm list:cypher`");
    return 1;
  }
  writeFileSync(README, readme.replace(now, next));
  console.log(`list:cypher: ${queries().length} files listed in README.md`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exitCode = main();
